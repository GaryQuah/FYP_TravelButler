"""
This file is used to define configuration settings for the application, such as database connection details and collection names. 
This is to standardize naming across files preventing hardcoding of values in multiple places, and to allow for easy updates to 
configuration settings in the future.
"""
import os

from dotenv import load_dotenv

load_dotenv()

# MongoDB connection settings and collection names
MONGO_URL = os.environ["MONGO_URL"]
DATABASE_NAME = os.environ.get("DATABASE_NAME", "travelmate_db")

#Stores user authentication and profile information for login and personalization
USER_COLLECTION = os.environ.get("USER_COLLECTION", "users")
#stores user profile information such as name, email, and preferences
TRIP_COLLECTION = os.environ.get("TRIP_COLLECTION", "trips")
#Stores user itineraries generated by the AI assistant, including activity details and scheduling information
ITINERARY_COLLECTION = os.environ.get("ITINERARY_COLLECTION", "itineraries")
#Stores chat history and messages for user interactions with the AI assistant
CHAT_COLLECTION = os.environ.get("CHATS_COLLECTION", "chats")
# Stores user budget preferences and limits for trip planning
BUDGET_COLLECTION = os.environ.get("BUDGET_COLLECTION", "budgets")
# Stores user availability data for scheduling purposes (e.g. free time slots)
AVAILABILITY_COLLECTION = os.environ.get("AVAILABILITY_COLLECTION", "availability") 
# Stores poll data for group decision making (e.g. voting on activities or dates)
POLL_COLLECTION = os.environ.get("POLL_COLLECTION", "polls")
# Stores user integration data such as services and tokens for external APIs (e.g. Google Calendar)
INTEGRATIONS_COLLECTION = os.environ.get("INTEGRATIONS_COLLECTION", "integrations")

DEBUG = os.environ.get("DEBUG", "").strip().lower() in {"1", "true", "on", "yes"}